{
	const float w = kGlyphW * scale;
	const float h = kGlyphH * scale;
	const float du = 1.0f / kCount;

	float pen = x;
	for (size_t i = 0; i < text.size(); ++i)
	{
		int code = static_cast<unsigned char>(text[i]);
		if (code < kFirst || code >= kFirst + kCount)
		{
			pen += w;
			continue;
		}

		float u0 = (code - kFirst) * du;
		float u1 = u0 + du;

		// Two triangles. Half a texel of inset keeps neighbouring glyphs from bleeding in under nearest sampling
		const float inset = 0.25f / (kGlyphW * kCount);
		u0 += inset;
		u1 -= inset;

		float quad[6][4] = {
			{ pen,     y,     u0, 0.0f },
			{ pen,     y + h, u0, 1.0f },
			{ pen + w, y + h, u1, 1.0f },
			{ pen,     y,     u0, 0.0f },
			{ pen + w, y + h, u1, 1.0f },
			{ pen + w, y,     u1, 0.0f },
		};

		for (int v = 0; v < 6; ++v)
			for (int c = 0; c < 4; ++c)
				out.push_back(quad[v][c]);

		pen += w;
	}
}

void TextRenderer::Draw(const std::string& text, float x, float y, float scale, glm::vec3 color)
{
	if (text.empty() || m_width <= 0)
		return;

	std::vector<float> verts;
	verts.reserve(text.size() * 24);
	Push(verts, text, x, y, scale);
	if (verts.empty())
		return;

	glBindBuffer(GL_ARRAY_BUFFER, m_vbo);
	glBufferData(GL_ARRAY_BUFFER, verts.size() * sizeof(float), verts.data(), GL_DYNAMIC_DRAW);

	GLsizei count = static_cast<GLsizei>(verts.size() / 4);

	// A dark pass one pixel down and right, so the text stays readable on top of bright orbital as well as on the background.
	glUniform3f(m_colorLoc, 0.0f, 0.0f, 0.0f);
	std::vector<float> shadow;
	shadow.reserve(verts.size());
	Push(shadow, text, x + scale, y + scale, scale);
	glBufferData(GL_ARRAY_BUFFER, shadow.size() * sizeof(float), shadow.data(), GL_DYNAMIC_DRAW);
	glDrawArrays(GL_TRIANGLES, 0, count);

	glUniform3fv(m_colorLoc, 1, glm::value_ptr(color));
	glBufferData(GL_ARRAY_BUFFER, verts.size() * sizeof(float), verts.data(), GL_DYNAMIC_DRAW);
	glDrawArrays(GL_TRIANGLES, 0, count);
}

void TextRenderer::DrawAnchored(const std::string& text, Anchor anchor, int line,
	float scale, glm::vec3 color, float margin)
{
	if (m_width <= 0 || m_height <= 0)
		return;

	float w = TextWidth(text, scale);
	float lh = LineHeight(scale);

	float x = margin;
	float y = margin + line * lh;

	if (anchor == Anchor::TopRight || anchor == Anchor::BottomRight)
		x = m_width - margin - w;

	if (anchor == Anchor::BottomLeft || anchor == Anchor::BottomRight)
		y = m_height - margin - (line + 1) * lh;

	Draw(text, x, y, scale, color);
}
