TextRenderer::TextRenderer()
{
	GLuint vs = Compile(GL_VERTEX_SHADER, kVertex);
	GLuint fs = Compile(GL_FRAGMENT_SHADER, kFragment);

	m_program = glCreateProgram();
	glAttachShader(m_program, vs);
	glAttachShader(m_program, fs);
	glLinkProgram(m_program);
	glDeleteShader(vs);
	glDeleteShader(fs);

	m_projLoc = glGetUniformLocation(m_program, "u_projection");
	m_colorLoc = glGetUniformLocation(m_program, "u_color");

	glUseProgram(m_program);
	glUniform1i(glGetUniformLocation(m_program, "u_font"), 0);

	// Unpack the bitmap into one long strip, kCount glyphs wide.
	const int width = kGlyphW * kCount;
	std::vector<unsigned char> pixels(static_cast<size_t>(width) * kGlyphH, 0);

	for (int g = 0; g < kCount; ++g)
		for (int row = 0; row < kGlyphH; ++row)
		{
			unsigned char bits = kFont[g * kGlyphH + row];
			for (int col = 0; col < kGlyphW; ++col)
				if (bits & (0x80 >> col))
					pixels[static_cast<size_t>(row) * width + g * kGlyphW + col] = 255;
		}

	glGenTextures(1, &m_texture);
	glBindTexture(GL_TEXTURE_2D, m_texture);
	glPixelStorei(GL_UNPACK_ALIGNMENT, 1); // rows are not multiples of four
	glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, width, kGlyphH, 0, GL_RED, GL_UNSIGNED_BYTE, pixels.data());
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
	glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
	glBindTexture(GL_TEXTURE_2D, 0);

	glGenVertexArrays(1, &m_vao);
	glBindVertexArray(m_vao);
	glGenBuffers(1, &m_vbo);
	glBindBuffer(GL_ARRAY_BUFFER, m_vbo);

	glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)0);
	glEnableVertexAttribArray(0);
	glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)(2 * sizeof(float)));
	glEnableVertexAttribArray(1);

	glBindVertexArray(0);
	glBindBuffer(GL_ARRAY_BUFFER, 0);
}

TextRenderer::~TextRenderer()
{
	glDeleteBuffers(1, &m_vbo);
	glDeleteVertexArrays(1, &m_vao);
	glDeleteTextures(1, &m_texture);
	glDeleteProgram(m_program);
}

void TextRenderer::Begin(int width, int height)
{
	m_width = width;
	m_height = height;
	if (width <= 0 || height <= 0)
		return;

	m_depthWasOn = glIsEnabled(GL_DEPTH_TEST);
	glDisable(GL_DEPTH_TEST);

	// Pixel coordinates with the origin at the top-left corner.
	glm::mat4 projection = glm::ortho(0.0f, static_cast<float>(width),
		static_cast<float>(height), 0.0f, -1.0f, 1.0f);

	glUseProgram(m_program);
	glUniformMatrix4fv(m_projLoc, 1, GL_FALSE, glm::value_ptr(projection));

	glActiveTexture(GL_TEXTURE0);
	glBindTexture(GL_TEXTURE_2D, m_texture);
	glBindVertexArray(m_vao);
}

void TextRenderer::End()
{
	glBindVertexArray(0);
	glBindTexture(GL_TEXTURE_2D, 0);

	if (m_depthWasOn)
		glEnable(GL_DEPTH_TEST);
}

